"""Independent addition diagnostics; stdout only, never edits the fixed benchmark.

Run: .venv/bin/python scripts/audit_addition_consistency.py
Expectations below are hand-specified connectivity/CIP relationships, not
generated by the production transform. Diagram/run outcomes are separate.
"""
import json
import sys
from collections import Counter
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from rdkit import Chem, RDLogger
from server import chemistry_server as service
from server.reaction_diagrams import _species

MODELS = {
    "Hydration": ("water", {"catalyst": "acid", "solvent": "aqueous-protic"}),
    "Hydrohalogenation": ("hydrogen-bromide", {"solvent": "dry"}),
    "Bromination": ("bromine", {"solvent": "dry"}),
    "Chlorination": ("chlorine", {"solvent": "dry"}),
    "Epoxidation": ("peracetic-acid", {"solvent": "dry"}),
    "Alkene dihydroxylation": ("hydrogen-peroxide", {"catalyst": "osmium", "workup": "aqueous-release"}),
}


def sites(options):
    """Count mapped C=C identities, not options/enantiomers; expand aliases."""
    return sorted({tuple(sorted(alias[:2])) for option in options
                   for alias in option["optionIdentity"]["siteAliases"] if len(alias) >= 2})


def canonical(smiles):
    molecule = Chem.MolFromSmiles(smiles)
    for atom in molecule.GetAtoms(): atom.SetAtomMapNum(0)
    return Chem.MolToSmiles(molecule, isomericSmiles=False)


def stereo_pairs(options):
    result = set()
    for option in options:
        local = set(option["site"]["atomMaps"][:2])
        centers = option["stereochemistry"]["product"]["chiralCenters"]
        result.add(tuple(sorted(c["assignment"] for c in centers if c["atomMap"] in local and c["specified"])))
    return sorted(result)


def inspect_option(option, substrate, reagent, conditions):
    """Do not let a run gate overwrite a verified 2D diagram observation."""
    row = {"id": option["id"], "diagram": {"status": "not-run"}, "run": {"status": "not-run"}, "failures": []}
    def check(ok, message):
        if not ok: row["failures"].append(message)
    d = None
    try:
        d = service.reaction_diagram(option["id"], substrate, reagent, conditions)
        row["diagram"] = {"status": "verified"}
        before = [a for a in d["atoms"] if a["side"] == "reactants"]
        after = [a for a in d["atoms"] if a["side"] == "products"]
        identity = lambda rows: Counter((a["mapId"], a["element"], a["formalCharge"]) for a in rows)
        check(identity(before) == identity(after), "Explicit atom/charge conservation")
        check(len({a["mapId"] for a in before}) == len(before) == len(d["atomMap"]), "Unique complete mapping")
        counts = (len(d["bondsFormed"]), len(d["bondsBroken"]), len(d["bondOrderChanges"]))
        check(counts == ((3, 2, 3) if option["mechanism"] == "Epoxidation" else (2, 1, 1)), "Net bond edit counts")
        check(option["stoichiometry"]["balanced"], "Balanced calculation basis")
        check(option["stoichiometry"]["context"]["assertionLevel"] == "conditional-net", "Conditional calculation context")
        origin = {a["mapId"]: a for a in before}
        for alias in option["optionIdentity"]["siteAliases"]:
            check(all(m in origin and origin[m]["element"] == "C" and origin[m]["speciesIndex"] == 0 for m in alias[:2]), "Site alias substrate atoms")
        p = option["site"]["parameters"]
        path = option["mechanism"]
        incoming = (p["bromines"] if path == "Bromination" else p["chlorines"] if path == "Chlorination" else
                    [p["transferredOxygen"]] if path == "Epoxidation" else
                    p["oxygens"] + p["hydroxylHydrogens"] if path == "Alkene dihydroxylation" else
                    [p["hydrogen"], p["halogen"]] if path == "Hydrohalogenation" else
                    [p["oxygen"], p["hydrogen"], p["hydroxylHydrogen"]])
        main_maps = {a["mapId"] for a in after if a["speciesIndex"] == 0}
        check(all(origin[m]["speciesIndex"] == 1 and m in main_maps for m in incoming), "Actual reagent atom provenance")
        mechanism = d["mechanism"]
        if option["mechanism"] == "Epoxidation":
            check(mechanism is not None and len(mechanism["steps"]) == 1, "One formal epoxide step")
            if mechanism:
                step = mechanism["steps"][0]
                check(step["concerted"] and step["intermediate"] is None and len(step["electronMoves"]) == 4, "No invented epoxide intermediate")
                sources = {frozenset(b["atomMaps"]) for b in step["beforeState"]["bonds"]}
                destinations = {frozenset(b["atomMaps"]) for b in step["state"]["bonds"]}
                check(all(frozenset(m["source"]["atomMaps"]) in sources and frozenset(m["destination"]["atomMaps"]) in destinations for m in step["electronMoves"]), "Explicit electron source/destination bonds")
        else:
            check(mechanism is None, "Net-only pathway must not invent a mechanism")
        row["mechanismSteps"] = len(mechanism["steps"]) if mechanism else 0
    except Exception as exc:
        row["diagram"] = {"status": "failed", "error": str(exc)}
        row["failures"].append("Unexpected diagram failure")
    permission = option["assessment"]["evidence"]["canGenerate3D"]
    try:
        model = service.run_curated_reaction(option["id"], substrate, reagent, conditions)["product"]
        row["run"] = {"status": "verified", "converged": model.get("converged")}
        check(permission, "Run permitted against evidence contract")
        check(model["smiles"] == option["productSmiles"], "Exact 3D product identity")
        if d:
            links = [(a["atomIndex"], a["mapId"], a["element"]) for a in d["atoms"] if a["side"] == "products" and a["speciesIndex"] == 0]
            check(links == [(a["index"], a["mapId"], a["element"]) for a in model["atomLinks"]], "2D/3D map correspondence")
        coordinates = Chem.MolFromMolBlock(model["molfile"], removeHs=False)
        for atom in coordinates.GetAtoms(): atom.SetAtomMapNum(0)
        Chem.AssignStereochemistryFrom3D(coordinates, replaceExistingTags=True)
        Chem.AssignStereochemistry(coordinates, cleanIt=True, force=True)
        Chem.AssignCIPLabels(coordinates)
        indices = {a["mapId"]: a["index"] for a in model["atomLinks"]}
        for center in option["stereochemistry"]["product"]["chiralCenters"]:
            if center["specified"]:
                atom = coordinates.GetAtomWithIdx(indices[center["atomMap"]])
                check(atom.HasProp("_CIPCode") and atom.GetProp("_CIPCode") == center["assignment"], "Independent coordinate CIP representation")
        _, custom, _ = service._resolve_reactants(substrate, reagent)
        catalog = {**service.REACTANTS, **custom}
        first = option["equationReactants"][0]
        original, _ = _species(first, catalog[first], 1)
        for link in model["atomLinks"]: coordinates.GetAtomWithIdx(link["index"]).SetAtomMapNum(link["mapId"])
        mapped = {a.GetAtomMapNum(): a for a in coordinates.GetAtoms()}
        def parity(atom):
            numbers = [a.GetAtomMapNum() for a in atom.GetNeighbors()]
            inversions = sum(numbers[i] > numbers[j] for i in range(len(numbers)) for j in range(i+1, len(numbers))) % 2
            return bool(inversions) ^ (atom.GetChiralTag() == Chem.ChiralType.CHI_TETRAHEDRAL_CW)
        for atom in original["mol"].GetAtoms():
            if atom.GetChiralTag() in {Chem.ChiralType.CHI_TETRAHEDRAL_CW, Chem.ChiralType.CHI_TETRAHEDRAL_CCW}:
                check(parity(atom) == parity(mapped[atom.GetAtomMapNum()]), "Distant physical configuration retention")
        selected = set(option["site"]["atomMaps"][:2])
        for bond in original["mol"].GetBonds():
            maps = {bond.GetBeginAtom().GetAtomMapNum(), bond.GetEndAtom().GetAtomMapNum()}
            if bond.GetBondTypeAsDouble() == 2 and maps != selected:
                a, b = maps
                check(coordinates.GetBondBetweenAtoms(indices[a], indices[b]).GetBondTypeAsDouble() == 2, "Unselected double bond preserved")
    except service.ChemistryError as exc:
        row["run"] = {"status": "blocked" if not permission else "failed", "error": str(exc)}
        check(not permission, "Unexpected blocked run")
    except Exception as exc:
        row["run"] = {"status": "failed", "error": str(exc)}
        row["failures"].append("Unexpected generation failure")
    return row


def build_cases():
    cases = []
    propene = {"Hydration": "CC(O)C", "Hydrohalogenation": "CC(Br)C", "Bromination": "BrCC(Br)C",
               "Chlorination": "ClCC(Cl)C", "Epoxidation": "CC1CO1", "Alkene dihydroxylation": "CC(O)CO"}
    internal = {"Hydration": ["CC(O)CCC", "CCC(O)CC"], "Hydrohalogenation": ["CC(Br)CCC", "CCC(Br)CC"],
                "Bromination": ["CC(Br)C(Br)CC"], "Chlorination": ["CC(Cl)C(Cl)CC"],
                "Epoxidation": ["CC1OC1CC"], "Alkene dihydroxylation": ["CC(O)C(O)CC"]}
    for path in MODELS:
        cases.append(dict(label="propene", path=path, smiles="C=CC", products=[propene[path]], site_count=1))
        cases.append(dict(label="unknown internal geometry", path=path, smiles="CC=CCC", products=internal[path], site_count=1, unsigned=True))
        cases.append(dict(label="missing settings", path=path, smiles="C=CC", products=[propene[path]], site_count=1, conditions={}))
        cases.append(dict(label="conjugated negative", path=path, smiles="C=CC=C", products=[], site_count=0))
    for path in ("Bromination", "Chlorination", "Epoxidation", "Alkene dihydroxylation"):
        anti = path in {"Bromination", "Chlorination"}
        for source, geometry in [("C/C=C/C", "E"), ("C/C=C\\C", "Z")]:
            expected = [("R", "S")] if (anti and geometry == "E") or (not anti and geometry == "Z") else [("R", "R"), ("S", "S")]
            cases.append(dict(label=geometry + "-2-butene", path=path, smiles=source, local_cips=expected, site_count=1))
        cyclic_products = {"Bromination": "BrC1C(Br)CCCC1", "Chlorination": "ClC1C(Cl)CCCC1",
                           "Epoxidation": "C1CCC2OC2C1", "Alkene dihydroxylation": "OC1C(O)CCCC1"}
        cases.append(dict(label="independent cyclic stereo", path=path, smiles="C1=CCCCC1", products=[cyclic_products[path]],
                          local_cips=[("R", "R"), ("S", "S")] if anti else [("R", "S")], site_count=1))
    for path in MODELS:
        cases.append(dict(label="far equivalent sites", path=path, smiles="C=CCCCCCCCCC=C", site_count=2))
        cases.append(dict(label="distant CIP-priority change", path=path, smiles="C=CCC[C@H](C)CCC(C)(C)C", site_count=1))
    return cases


def run_audit():
    results = []
    failures = []
    for case in build_cases():
        path = case["path"]
        reagent, model = MODELS[path]
        conditions = case.get("conditions", model)
        substrate = {"smiles": case["smiles"], "name": "Independent addition diagnostic"}
        response = service.match_reactions(substrate, reagent, conditions)
        options = [o for o in response["reactionOptions"] if o["mechanism"] == path]
        row = {"path": path, "label": case["label"], "source": case["smiles"], "optionCount": len(options),
               "sites": sites(options), "failures": [], "options": []}
        if len(row["sites"]) != case["site_count"]: row["failures"].append("Independent site count")
        if "products" in case and {canonical(o["productSmiles"]) for o in options} != {canonical(s) for s in case["products"]}:
            row["failures"].append("Independent product connectivity")
        if "local_cips" in case and stereo_pairs(options) != sorted(case["local_cips"]): row["failures"].append("Independent local CIP expectation")
        if case.get("unsigned") and any(c["specified"] for o in options for c in o["stereochemistry"]["product"]["chiralCenters"]):
            row["failures"].append("Unknown geometry acquired a configuration")
        for option in options:
            observed = inspect_option(option, substrate, reagent, conditions)
            row["options"].append(observed)
            row["failures"].extend(observed["failures"])
        if row["failures"]: failures.append({"path": path, "label": case["label"], "failures": row["failures"]})
        results.append(row)
    return {"version": 1, "fixedBenchmarkModified": False, "caseCount": len(results),
            "optionCount": sum(r["optionCount"] for r in results), "failures": failures, "results": results}


if __name__ == "__main__":
    RDLogger.DisableLog("rdApp.warning")
    result = run_audit()
    print(json.dumps(result, separators=(",", ":")))
    raise SystemExit(bool(result["failures"]))
